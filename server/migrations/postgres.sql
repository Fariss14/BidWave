CREATE SCHEMA IF NOT EXISTS bidwave;
SET search_path TO bidwave;
    CREATE TABLE IF NOT EXISTS users (
      id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL,
      name TEXT NOT NULL, password_hash TEXT NOT NULL, created_at BIGINT NOT NULL
    , rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at BIGINT NOT NULL
    , rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE INDEX IF NOT EXISTS sessions_by_user ON sessions(user_id);
    CREATE TABLE IF NOT EXISTS auctions (id TEXT PRIMARY KEY, data TEXT NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE TABLE IF NOT EXISTS addresses (
      user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, data TEXT NOT NULL
    , rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE TABLE IF NOT EXISTS orders (
      id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id),
      auction_id TEXT UNIQUE, data TEXT NOT NULL
    , rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE INDEX IF NOT EXISTS order_user ON orders(user_id);
    CREATE TABLE IF NOT EXISTS payments (
      id TEXT PRIMARY KEY, order_id TEXT UNIQUE NOT NULL REFERENCES orders(id),
      user_id TEXT NOT NULL REFERENCES users(id), data TEXT NOT NULL,
      proof BYTEA NOT NULL, mime TEXT NOT NULL, filename TEXT NOT NULL
    , rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE TABLE IF NOT EXISTS refund_proofs (order_id TEXT PRIMARY KEY REFERENCES orders(id), proof BYTEA NOT NULL, mime TEXT NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE TABLE IF NOT EXISTS payment_history (id TEXT PRIMARY KEY, order_id TEXT NOT NULL REFERENCES orders(id), user_id TEXT NOT NULL REFERENCES users(id), data TEXT NOT NULL, proof BYTEA NOT NULL, mime TEXT NOT NULL, filename TEXT NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE INDEX IF NOT EXISTS payment_user ON payments(user_id);
    CREATE TABLE IF NOT EXISTS categories (id TEXT PRIMARY KEY, name TEXT NOT NULL, normalized TEXT UNIQUE NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE TABLE IF NOT EXISTS media (id TEXT PRIMARY KEY, owner_id TEXT NOT NULL REFERENCES users(id), kind TEXT NOT NULL, bytes BYTEA NOT NULL, mime TEXT NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE TABLE IF NOT EXISTS seller_settings (user_id TEXT PRIMARY KEY REFERENCES users(id), data TEXT NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE TABLE IF NOT EXISTS finalized_auctions (auction_id TEXT PRIMARY KEY REFERENCES auctions(id), finalized_at BIGINT NOT NULL, rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE TABLE IF NOT EXISTS notifications (
      id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), auction_id TEXT NOT NULL,
      type TEXT NOT NULL, data TEXT NOT NULL, read_at BIGINT,
      UNIQUE(user_id, auction_id, type)
    , rowid BIGINT GENERATED BY DEFAULT AS IDENTITY);
    CREATE INDEX IF NOT EXISTS notification_user ON notifications(user_id);


REVOKE ALL ON SCHEMA bidwave FROM PUBLIC;

CREATE INDEX IF NOT EXISTS history_order ON payment_history(order_id);
